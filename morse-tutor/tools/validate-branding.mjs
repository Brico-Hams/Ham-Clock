// Static regression checks for boot branding and user-configurable callsign.
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const source = readFileSync(new URL('../src/main.cpp', import.meta.url), 'utf8');
const config = readFileSync(new URL('../include/NetworkProtocol.h', import.meta.url), 'utf8');
const image = readFileSync(new URL('../src/bricohams_logo.h', import.meta.url), 'utf8');
const boardIO = readFileSync(new URL('../src/board_io.cpp', import.meta.url), 'utf8');
const board = readFileSync(new URL('../include/BoardConfig.h', import.meta.url), 'utf8');
assert.match(source, /char callsign\[brico::kCallSize\] = "NOCALL";/);
assert.match(source, /storage\.getString\("call", "NOCALL"\)/);
assert.match(source, /storage\.putString\("call", config\.callsign\)/);
assert.match(source, /text\(config\.callsign, DISPLAY_W - callWidth - 8, 12, 2, kAccent\)/);
assert.match(source, /drawHomeBrand\(\)/);
assert.match(source, /brico_logo::draw\(display, .*width, height,/);
assert.match(source, /brico_logo::draw\(display, 9, 4, 32, 32, 0, 112, true, true, kBackground\)/);
assert.match(source, /display\.fillScreen\(kBackground\)/);
assert.doesNotMatch(source, /display\.fillRect\(6, 3, 174, 34, TFT_WHITE\)/);
assert.match(source, /paintedActivity == activity/);
assert.match(source, /const bool paddles = !receiveActivity\(\) && !touchKeyScreen\(\)/);
assert.match(source, /footer\(first, second, third, paddles \? "DIT" : "", paddles \? "DAH" : ""\)/);
assert.match(source, /footer\("-", "\+", tr\(Text::Save\), "", ""\)/);
assert.match(board, /#if BRICO_PANEL == 778932[\s\S]*?#define SPI_FREQUENCY 40000000[\s\S]*?#elif BRICO_PANEL == 7796/);
assert.match(image, /transparentWhite && colourIndex == 0/);
assert.match(image, /\? matteColor/);
assert.doesNotMatch(image, /pushImage\(x, y \+ outputY, outputWidth, 1, outputLine, TFT_WHITE\)/);
assert.match(image, /tft\.setSwapBytes\(savedSwap\)/);
assert.doesNotMatch(source, /void brandEmblem\(/);
const packed = image.match(/R"BH\(([^)]+)\)BH"/)?.[1];
assert(packed, 'RGB565 RLE logo data missing');
const runs = Buffer.from(packed, 'base64');
assert.equal(runs.reduce((sum, b) => sum + (b >> 2), 0), 300 * 112, 'image must cover every pixel');
assert.match(image, /tft\.setSwapBytes\(true\)/);
assert.match(source, /void drawBootLogo\(\)/);
assert.match(source, /drawBootLogo\(\);[\s\S]*while \(millis\(\) - logoShownAt < 1900\)/);
const startup = source.substring(source.indexOf('void setup() {'), source.indexOf('void loop() {'));
assert.match(startup, /while \(millis\(\) - logoShownAt < 1900\) delay\(10\);\s*[\s\S]*?board::setBrightness\(0\);\s*render\(\);\s*board::setBrightness\(config\.brightness\);/);
assert.match(boardIO, /constrain\(percent, 0, 100\)/);
assert(!startup.includes('redraw = true;'), 'Startup should draw full home before enabling backlight');
assert.doesNotMatch(source, /text\("MORSE TUTOR /);
assert.doesNotMatch(source, /"AO5BH"/);
assert.match(config, /constexpr size_t kCallSize = 10;/);
console.log('PASS: startup branding and persisted configurable callsign');
